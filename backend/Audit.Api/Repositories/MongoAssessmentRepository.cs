using System.Collections.Generic;
using System.Threading.Tasks;
using Audit.Api.Models;
using MongoDB.Driver;

namespace Audit.Api.Repositories;

/// <summary>
/// Data Access Layer for MongoDB, strictly handling assessment persistence and retrieval without business logic.
/// </summary>
public class MongoAssessmentRepository : IAssessmentRepository
{
    private readonly IMongoCollection<Question> _questionsCollection;
    private readonly IMongoCollection<Assessment> _assessmentsCollection;

    /// <summary>
    /// Initializes a new instance of the MongoAssessmentRepository class.
    /// Injects the scoped MongoDB context and initializes direct connections to the necessary collections.
    /// </summary>
    /// <param name="dbContext">The MongoDB database context.</param>
    public MongoAssessmentRepository(MongoDbContext dbContext)
    {
        _questionsCollection = dbContext.Database.GetCollection<Question>("questions");
        _assessmentsCollection = dbContext.Database.GetCollection<Assessment>("assessments");
    }

    /// <summary>
    /// Retrieves a list of questions belonging to a specific quiz category.
    /// </summary>
    /// <param name="category">The category name to filter questions by (case-insensitive).</param>
    /// <returns>A list of questions matching the specified category.</returns>
    public async Task<List<Question>> GetQuestionsByCategoryAsync(string category)
    {
        // DATA ACCESS: Fetches questions using a case-insensitive MongoDB query to prevent casing mismatch errors.
        return await _questionsCollection.Find(q => q.QuizCategory.ToLower() == category.ToLower())
                                         .ToListAsync();
    }

    /// <summary>
    /// Persists a completed assessment record into the MongoDB database.
    /// </summary>
    /// <param name="assessment">The fully validated Assessment domain model generated by the Supervisor.</param>
    /// <returns>The saved assessment containing the generated database ID.</returns>
    public async Task<Assessment> SaveAssessmentAsync(Assessment assessment)
    {
        // DATA ACCESS: Directly persists the assessment document into MongoDB.
        await _assessmentsCollection.InsertOneAsync(assessment);
        return assessment;
    }

    /// <summary>
    /// Retrieves the assessment history for a specific user, ordered chronologically from most recent to oldest.
    /// </summary>
    /// <param name="username">The username whose history is being requested.</param>
    /// <returns>A descending-ordered list of completed assessments for the user.</returns>
    public async Task<List<Assessment>> GetHistoryByUsernameAsync(string username)
    {
        // DATA ACCESS: Retrieves user history, leveraging MongoDB's native sorting to return the most recent first.
        return await _assessmentsCollection.Find(a => a.Username.ToLower() == username.ToLower())
                                           .SortByDescending(a => a.CompletedAt)
                                           .ToListAsync();
    }
}