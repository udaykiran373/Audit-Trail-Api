using System.Threading.Tasks;
using Audit.Api.Models;
using MongoDB.Driver;

namespace Audit.Api.Repositories;

/// <summary>
/// The Data Access Layer (Repository) for User Authentication.
/// Acts as Tier 3 in the 3-Tier Architecture. Its sole responsibility is 
/// executing direct database operations (MongoDB) without enforcing business rules 
/// (like password hashing or token generation), which strictly belong in the Supervisor layer.
/// </summary>
public class AuthRepository : IAuthRepository
{
    private readonly IMongoCollection<User> _usersCollection;

    /// <summary>
    /// Initializes a new instance of the AuthRepository.
    /// Injects the MongoDB context to establish a direct connection to the "users" collection.
    /// </summary>
    /// <param name="dbContext">The scoped MongoDB database context.</param>
    public AuthRepository(MongoDbContext dbContext)
    {
        _usersCollection = dbContext.Database.GetCollection<User>("users");
    }

    /// <summary>
    /// Checks if a user already exists in the database.
    /// Used by the Supervisor to prevent duplicate registrations.
    /// </summary>
    /// <param name="username">The raw username to check.</param>
    public async Task<bool> UserExistsAsync(string username)
    {
        // DATA ACCESS: Normalize the input to ensure a safe, case-insensitive match
        var usernameLower = username.Trim().ToLowerInvariant();

        // ARCHITECTURE NOTE: Uses AnyAsync() instead of fetching the whole user.
        // This is highly optimized at the database level—it stops searching the moment it finds one match.
        return await _usersCollection.Find(u => u.Username.ToLower() == usernameLower).AnyAsync();
    }

    /// <summary>
    /// Retrieves a user document based on their username.
    /// Used by the Supervisor during the login process to fetch the hashed password for comparison.
    /// </summary>
    /// <param name="username">The username to search for.</param>
    public async Task<User?> GetUserByUsernameAsync(string username)
    {
        // DATA ACCESS: Normalize the search string to prevent login failures due to accidental casing
        var usernameLower = username.Trim().ToLowerInvariant();

        // Execute the fetch and return the document (or null if not found) directly to the Supervisor
        return await _usersCollection.Find(u => u.Username.ToLower() == usernameLower).FirstOrDefaultAsync();
    }

    /// <summary>
    /// Persists a newly constructed and hashed User entity to the MongoDB database.
    /// </summary>
    /// <param name="user">The fully validated User model generated by the Supervisor.</param>
    public async Task<User> CreateUserAsync(User user)
    {
        // DATA ACCESS: Insert the validated domain model directly into the MongoDB collection.
        // ARCHITECTURE NOTE: Password hashing is intentionally NOT done here. 
        // The Repository strictly assumes the Supervisor has already sanitized and hashed the password.
        await _usersCollection.InsertOneAsync(user);

        return user;
    }
}