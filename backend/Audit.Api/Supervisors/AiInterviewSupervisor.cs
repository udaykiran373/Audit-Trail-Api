using System;
using System.IO;
using System.Collections.Generic;
using System.Threading.Tasks;
using Microsoft.AspNetCore.Hosting;
using Audit.Api.Models;
using Audit.Api.Repositories;
using Audit.Api.DTOs;

namespace Audit.Api.Supervisors
{
    /// <summary>
    /// The Business Logic Layer (Supervisor) for AI Interview workflows.
    /// Orchestrates file system operations (video storage), domain model construction, 
    /// database persistence, and cross-cutting concerns (Audit Logging).
    /// </summary>
    public class AiInterviewSupervisor : IAiInterviewSupervisor
    {
        private readonly IAiInterviewRepository _repository;
        private readonly IAuditLogRepository _auditRepository;
        private readonly IWebHostEnvironment _env;

        public AiInterviewSupervisor(IAiInterviewRepository repository, IAuditLogRepository auditRepository, IWebHostEnvironment env)
        {
            _repository = repository;
            _auditRepository = auditRepository;
            _env = env;
        }

        /// <summary>
        /// Orchestrates the submission of an AI interview. Handles video file streaming to disk,
        /// constructs the domain model, saves it to the database, and emits an Audit Log.
        /// </summary>
        public async Task<object> SubmitInterviewAsync(string username, string role, string question, string? transcript, int warningsCount, string? warningsLogJson, Microsoft.AspNetCore.Http.IFormFile? videoFile, string ipAddress, string userAgent, string correlationId, string sessionId, string requestPath)
        {
            string videoUrl = "";

            // Securely stream the uploaded video to the server's local file system without buffering the whole file in RAM.
            if (videoFile != null && videoFile.Length > 0)
            {
                var uploadDir = Path.Combine(_env.WebRootPath ?? Path.Combine(Directory.GetCurrentDirectory(), "wwwroot"), "uploads", "interviews");
                Directory.CreateDirectory(uploadDir);

                var fileName = $"{Guid.NewGuid()}_{videoFile.FileName}";
                if (string.IsNullOrEmpty(Path.GetExtension(videoFile.FileName)))
                {
                    fileName += ".webm"; // Fallback to WebM if the browser didn't provide an extension
                }

                using (var stream = new FileStream(Path.Combine(uploadDir, fileName), FileMode.Create))
                {
                    await videoFile.CopyToAsync(stream);
                }
                videoUrl = $"/uploads/interviews/{fileName}";
            }

            // BUSINESS LOGIC: Sanitize and deserialize JSON warnings generated by the frontend proctoring engine
            var warningsLog = new List<string>();
            try
            {
                if (!string.IsNullOrWhiteSpace(warningsLogJson))
                {
                    warningsLog = System.Text.Json.JsonSerializer.Deserialize<List<string>>(warningsLogJson) ?? new();
                }
            }
            catch { } // Graceful fallback: If JSON is corrupted, default to an empty list rather than crashing

            // Placeholders for future AI processing integration
            var score = "Pending";
            var aiFeedback = "Analysis queued. Video and transcript have been securely captured.";

            // Construct the validated Domain Model
            var interviewRecord = new AiInterview
            {
                Username = username,
                RoleAppliedFor = role,
                QuestionText = question,
                CandidateTranscript = transcript,
                Score = score,
                AiFeedback = aiFeedback,
                VideoUrl = videoUrl,
                WarningsCount = warningsCount,
                WarningsLog = warningsLog
            };

            // Delegate persistence to the Data Access Layer
            await _repository.SaveInterviewAsync(interviewRecord);

            // CROSS-CUTTING CONCERN: Ensure an immutable Audit Log is written for this critical action
            await _auditRepository.InsertAsync(new AuditLog
            {
                Timestamp = DateTime.UtcNow,
                UserId = username,
                SessionId = sessionId,
                EventType = "Interview",
                Module = "Completed",
                Status = "SUCCESS",
                CorrelationId = correlationId,
                RequestPath = requestPath,
                IpAddress = ipAddress,
                UserAgent = userAgent,
                Metadata = new Dictionary<string, object> {
                    { "InterviewId", interviewRecord.Id ?? "" },
                    { "Role", role },
                    { "Score", score },
                    { "Warnings", warningsCount }
                }
            });

            return new { Message = "Interview processed successfully", Score = score, Feedback = aiFeedback, WarningsCount = warningsCount };
        }

        /// <summary>
        /// Retrieves the interview history for a specific user.
        /// </summary>
        public async Task<List<AiInterview>> GetHistoryByUsernameAsync(string username)
        {
            return await _repository.GetHistoryByUsernameAsync(username);
        }

        /// <summary>
        /// Emits a telemetry Audit Log when a user accesses the AI Interview dashboard.
        /// </summary>
        public async Task LogViewAsync(string username, string ipAddress, string userAgent, string correlationId, string sessionId, string requestPath)
        {
            // BUSINESS LOGIC: Centralized telemetry logging
            await _auditRepository.InsertAsync(new AuditLog
            {
                Timestamp = DateTime.UtcNow,
                UserId = username,
                SessionId = sessionId,
                EventType = "Interview",
                Module = "Opened",
                Status = "SUCCESS",
                CorrelationId = correlationId,
                RequestPath = requestPath,
                IpAddress = ipAddress,
                UserAgent = userAgent,
                Metadata = new Dictionary<string, object>()
            });
        }

        /// <summary>
        /// Emits a security Audit Log detailing whether the user granted or denied hardware permissions (Camera/Mic).
        /// </summary>
        public async Task LogPermissionsAsync(PermissionsPayload payload, string username, string ipAddress, string userAgent, string correlationId, string sessionId, string requestPath)
        {
            // BUSINESS LOGIC: Determine the logical status and action based on the payload boolean
            var status = payload.Granted ? "SUCCESS" : "FAILED";
            var action = payload.Granted ? "PermissionsGranted" : "PermissionsDenied";

            var log = new AuditLog
            {
                Timestamp = DateTime.UtcNow,
                UserId = username,
                SessionId = sessionId,
                EventType = "Interview",
                Module = action,
                Status = status,
                CorrelationId = correlationId,
                RequestPath = requestPath,
                IpAddress = ipAddress,
                UserAgent = userAgent,
                Metadata = new Dictionary<string, object>
                {
                    { "CameraGranted", payload.CameraGranted },
                    { "MicrophoneGranted", payload.MicrophoneGranted }
                }
            };

            await _auditRepository.InsertAsync(log);
        }
    }
}